def save_to_json(terms, output_path="data/glossary_zh_kh_spoken.json"):
    """Saves terms to clean UTF-8 JSON file"""
    out_file = Path(output_path)
    out_file.parent.mkdir(parents=True, exist_ok=True)
    
    data = [
        {"zh_term": zh, "kh_term": kh, "category": cat}
        for zh, kh, cat in terms
    ]
