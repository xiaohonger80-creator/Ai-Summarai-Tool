import os
import re
from pathlib import Path
from typing import List, Dict, Any, Optional


class TextAnimator:
    """
    Advanced SubStation Alpha (.ass) Animation Engine for VideoFX Studio:
    - Generates UTF-8 with BOM (.ass) scripts for 100% Windows Unicode compatibility.
    - Full support for Khmer (Khmer OS Battambang, Noto Sans Khmer), Chinese (Microsoft YaHei), and English.
    - 4 Animation Modes:
      1. Horizontal Scrolling Marquee (អក្សររត់ដេក)
      2. Vertical Credits Roll (អក្សររត់ឡើងលើ)
      3. Kinetic Bounce / Pop-In (អក្សរលោត)
      4. Neon Glow / Boxed Banner (បដាមានស៊ុម និងពន្លឺ Neon)
    """

    ANIMATION_MODES = [
        "Horizontal Scrolling Marquee (អក្សររត់ដេក)",
        "Vertical Credits Roll (អក្សររត់ឡើងលើ)",
        "Kinetic Bounce / Pop-In (អក្សរលោត)",
        "Neon Glow / Boxed Banner (បដាពន្លឺ)",
    ]

    @staticmethod
    def hex_to_ass_color(hex_str: str, alpha: int = 0) -> str:
        """
        Converts #RRGGBB or #AARRGGBB to ASS &HAABBGGRR format.
        """
        clean = hex_str.strip().lstrip("#")
        if len(clean) == 8:
            a, r, g, b = clean[0:2], clean[2:4], clean[4:6], clean[6:8]
            return f"&H{a.upper()}{b.upper()}{g.upper()}{r.upper()}&"
        elif len(clean) == 6:
            r, g, b = clean[0:2], clean[2:4], clean[4:6]
            a_hex = f"{alpha:02X}"
            return f"&H{a_hex}{b.upper()}{g.upper()}{r.upper()}&"
        return "&H00FFFFFF&"

    @staticmethod
    def _sec_to_ass_time(sec: float) -> str:
        s = max(0.0, float(sec))
        hrs = int(s // 3600)
        mins = int((s % 3600) // 60)
        secs = int(s % 60)
        cs = int(round((s - int(s)) * 100))
        if cs >= 100:
            cs = 99
        return f"{hrs:d}:{mins:02d}:{secs:02d}.{cs:02d}"

    @classmethod
    def generate_ass_script(
        cls,
        text_content: str,
        animation_mode: str,
        video_duration_sec: float,
        out_ass_path: str,
        width: int = 1920,
        height: int = 1080,
        font_name: str = "Noto Sans Khmer",
        font_size: int = 48,
        primary_color: str = "#FFFFFF",
        outline_color: str = "#000000",
        box_bg_color: str = "#0B0D10",
        position: str = "Bottom",  # "Top", "Middle", "Bottom"
        speed_factor: float = 1.0,
        segments: List[Dict[str, Any]] = None,
    ) -> str:
        """
        Generates and saves a complete, valid .ass script with UTF-8 BOM encoding.
        Returns the absolute path to the generated .ass file.
        """
        out_p = Path(out_ass_path)
        out_p.parent.mkdir(parents=True, exist_ok=True)

        primary_ass = cls.hex_to_ass_color(primary_color, alpha=0)
        outline_ass = cls.hex_to_ass_color(outline_color, alpha=0)
        back_ass = cls.hex_to_ass_color(box_bg_color, alpha=60)  # semi-transparent box

        # Alignments in ASS:
        # 1=Bottom-Left, 2=Bottom-Center, 3=Bottom-Right
        # 4=Mid-Left,    5=Mid-Center,    6=Mid-Right
        # 7=Top-Left,    8=Top-Center,    9=Top-Right
        pos_lower = position.lower()
        if "top" in pos_lower:
            y_base = int(height * 0.12)
            alignment = 8
        elif "mid" in pos_lower:
            y_base = int(height * 0.50)
            alignment = 5
        else:
            y_base = int(height * 0.88)
            alignment = 2

        # Header section
        header = [
            "[Script Info]",
            "; Script generated by VideoFX Studio",
            "ScriptType: v4.00+",
            f"PlayResX: {width}",
            f"PlayResY: {height}",
            "WrapStyle: 0",
            "ScaledBorderAndShadow: yes",
            "",
            "[V4+ Styles]",
            "Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding",
        ]

        dialogue_lines: List[str] = []

        total_dur = max(2.0, float(video_duration_sec or 10.0))
        t_start_s = "0:00:00.00"
        t_end_s = cls._sec_to_ass_time(total_dur)

        # Mode 1: Horizontal Scrolling Marquee (អក្សររត់ដេក)
        if "horizontal" in animation_mode.lower() or "marquee" in animation_mode.lower():
            style_line = (
                f"Style: MarqueeStyle,{font_name},{font_size},{primary_ass},&H000000FF&,{outline_ass},{back_ass},"
                f"-1,0,0,0,100,100,0,0,1,3,2,{alignment},20,20,30,1"
            )
            header.append(style_line)

            text_clean = text_content.replace("\n", "   ★   ").strip() or "★ AI VideoFX Studio Marquee Banner ★"
            # Calculate duration per scroll loop
            char_count = len(text_clean)
            pixels = char_count * font_size * 0.65
            loop_dur = max(4.0, (width + pixels) / (180.0 * max(0.2, speed_factor)))

            curr_t = 0.0
            while curr_t < total_dur:
                end_t = min(total_dur, curr_t + loop_dur)
                s_str = cls._sec_to_ass_time(curr_t)
                e_str = cls._sec_to_ass_time(end_t)

                x_start = width + 50
                x_end = -int(pixels + 50)
                anim = f"{{\\move({x_start}, {y_base}, {x_end}, {y_base})}}{text_clean}"
                dialogue_lines.append(f"Dialogue: 0,{s_str},{e_str},MarqueeStyle,,0,0,0,,{anim}")
                curr_t += loop_dur

        # Mode 2: Vertical Credits Roll (អក្សររត់ឡើងលើ)
        elif "vertical" in animation_mode.lower() or "credits" in animation_mode.lower():
            style_line = (
                f"Style: CreditsStyle,{font_name},{font_size},{primary_ass},&H000000FF&,{outline_ass},{back_ass},"
                f"-1,0,0,0,100,100,1,0,1,2,1,5,30,30,30,1"
            )
            header.append(style_line)

            formatted_text = text_content.replace("\n", "\\N") or "PRODUCED BY VIDEOFX STUDIO\\NDIRECTED BY AI\\NDUBBING & SUBTITLES"
            lines_count = text_content.count("\n") + 1
            roll_height = lines_count * (font_size + 16)

            roll_dur = max(5.0, (height + roll_height) / (75.0 * max(0.2, speed_factor)))
            curr_t = 0.0
            x_center = width // 2

            while curr_t < total_dur:
                end_t = min(total_dur, curr_t + roll_dur)
                s_str = cls._sec_to_ass_time(curr_t)
                e_str = cls._sec_to_ass_time(end_t)

                y_start = height + 50
                y_end = -int(roll_height + 50)
                anim = f"{{\\move({x_center}, {y_start}, {x_center}, {y_end})}}{formatted_text}"
                dialogue_lines.append(f"Dialogue: 0,{s_str},{e_str},CreditsStyle,,0,0,0,,{anim}")
                curr_t += roll_dur

        # Mode 3: Kinetic Bounce / Pop-In (អក្សរលោត)
        elif "kinetic" in animation_mode.lower() or "pop" in animation_mode.lower() or "bounce" in animation_mode.lower():
            style_line = (
                f"Style: KineticStyle,{font_name},{font_size},{primary_ass},&H000000FF&,{outline_ass},{back_ass},"
                f"-1,0,0,0,100,100,0,0,1,4,3,{alignment},25,25,45,1"
            )
            header.append(style_line)

            # If user provided timed segments, animate segment by segment
            if segments and len(segments) > 0:
                for s in segments:
                    s_t = cls._sec_to_ass_time(s["start"])
                    e_t = cls._sec_to_ass_time(s["end"])
                    txt = (s.get("translated") or s.get("text") or "").strip()
                    if txt:
                        # Pop-in scaling animation: 60% -> 115% -> 100% in 220ms
                        anim = f"{{\\fscx60\\fscy60\\t(0,140,\\fscx115\\fscy115)\\t(140,240,\\fscx100\\fscy100)}}{txt}"
                        dialogue_lines.append(f"Dialogue: 0,{s_t},{e_t},KineticStyle,,0,0,0,,{anim}")
            else:
                # Custom text split by lines or chunks
                chunks = [c.strip() for c in text_content.split("\n") if c.strip()] or ["Kinetic VideoFX Pop-In Text!"]
                chunk_dur = total_dur / len(chunks)
                for i, c in enumerate(chunks):
                    s_t = cls._sec_to_ass_time(i * chunk_dur)
                    e_t = cls._sec_to_ass_time((i + 1) * chunk_dur)
                    anim = f"{{\\fscx60\\fscy60\\t(0,140,\\fscx115\\fscy115)\\t(140,240,\\fscx100\\fscy100)}}{c}"
                    dialogue_lines.append(f"Dialogue: 0,{s_t},{e_t},KineticStyle,,0,0,0,,{anim}")

        # Mode 4: Neon Glow / Boxed Banner (បដាមានស៊ុម និងពន្លឺ Neon)
        else:
            # BorderStyle=3 gives a full opaque/translucent background box behind text
            style_line = (
                f"Style: NeonBoxStyle,{font_name},{font_size},{primary_ass},&H000000FF&,{outline_ass},{back_ass},"
                f"-1,0,0,0,100,100,0,0,3,6,4,{alignment},30,30,45,1"
            )
            header.append(style_line)

            txt = text_content.replace("\n", "\\N").strip() or "VIDEOFX STUDIO ★ LIVE BROADCAST"
            dialogue_lines.append(f"Dialogue: 0,{t_start_s},{t_end_s},NeonBoxStyle,,0,0,0,,{txt}")

        header.append("")
        header.append("[Events]")
        header.append("Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text")

        full_ass_text = "\n".join(header) + "\n" + "\n".join(dialogue_lines) + "\n"

        # Write with UTF-8 BOM (utf-8-sig) so libass and Windows text renderers never garble Unicode
        with open(out_p, "w", encoding="utf-8-sig") as f:
            f.write(full_ass_text)

        return str(out_p.resolve())
