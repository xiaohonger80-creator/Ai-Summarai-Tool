def ass_color_to_rgb(ass_str: str) -> Tuple[int, int, int]:
    """បំប្លែងពណ៌ ASS (&HAABBGGRR ឬ &HBBGGRR) ទៅជា (R, G, B)"""
    try:
        s = ass_str.replace("&H", "").replace("&h", "").replace("#", "").strip()
        if len(s) == 8:
            s = s[2:]  # drop AA
        if len(s) >= 6:
            b = int(s[0:2], 16)
            g = int(s[2:4], 16)
            r = int(s[4:6], 16)
            return r, g, b
    except Exception:
        pass
    return 255, 255, 255


def ass_color_to_rgba(ass_str: str) -> Tuple[int, int, int, int]:
    """បំប្លែងពណ៌ ASS (&HAABBGGRR) ទៅជា (R, G, B, Alpha 0-255 សម្រាប់ Qt)"""
    try:
        s = ass_str.replace("&H", "").replace("&h", "").replace("#", "").strip()
        if len(s) == 8:
            aa = int(s[0:2], 16)
            b = int(s[2:4], 16)
            g = int(s[4:6], 16)
            r = int(s[6:8], 16)
            # ក្នុង ASS: 00 = Opaque, FF = Transparent. ក្នុង Qt: 255 = Opaque, 0 = Transparent
            a = max(0, min(255, 255 - aa))
            return r, g, b, a
        elif len(s) >= 6:
            b = int(s[0:2], 16)
            g = int(s[2:4], 16)
            r = int(s[4:6], 16)
            return r, g, b, 255
    except Exception:
        pass
    return 0, 0, 0, 180

